# # Types of T-Test
# 1. One-Sample T-Test

# Used to compare the mean of a sample with a known population mean.

# Example:
# A company claims that the average battery life is 10 hours. A sample of 20 batteries is tested to verify the claim.

# 2. Independent Two-Sample T-Test

# Used to compare the means of two independent groups.

# Example:
# Compare the average marks of students taught using Method A and Method B.

# 3. Paired T-Test

# Used when the same subjects are measured before and after a treatment.

# Example:
# Compare students' test scores before and after attending a coaching program.

# Assumptions of T-Test
# Data is continuous (interval or ratio scale).
# Data is approximately normally distributed.
# Observations are independent.
# Population standard deviation is unknown.
# For an independent t-test, the two groups are independent.
# Hypotheses
# Null Hypothesis (H₀): There is no significant difference between the means.
# Alternative Hypothesis (H₁): There is a significant difference between the means.