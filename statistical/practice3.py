# Chi-Square (χ²) Test

# The Chi-Square (χ²) Test is a non-parametric statistical test used to determine whether there is a significant association between categorical variables or whether observed frequencies differ from expected frequencies.

# Definition

# The Chi-Square Test compares the observed (actual) frequencies with the expected frequencies to determine whether the differences are due to chance or are statistically significant.

# Types of Chi-Square Test
# Chi-Square Test of Independence
# Determines whether two categorical variables are associated.
# Example: Is there a relationship between gender and preference for a product?
# Chi-Square Goodness-of-Fit Test
# Determines whether observed data follow an expected distribution.
# Example: Is a die fair